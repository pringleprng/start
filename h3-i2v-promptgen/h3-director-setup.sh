def releases(repo: str, tag: str = "latest") -> list[dict]:
    """The given release, or the recent releases newest first (some releases lack some files)."""
    if tag != "latest":
        return [get_json(f"{GITHUB_API}/repos/{repo}/releases/tags/{tag}")]
