            f"Exec={desktop_quote(str(script))}\n"
            f"Icon={icon if icon.exists() else 'applications-multimedia'}\n"
            "Terminal=false\nCategories=Graphics;AudioVideo;\n", encoding="utf-8")
        say(f"  ✓ app menu: 'TextGen H3 Director' ({entry})")
    return script


