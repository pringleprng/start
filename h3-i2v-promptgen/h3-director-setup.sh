#
# Installs TextGen, a llama.cpp new enough for Inkling 2 (CUDA, RTX 50-series ready),
# Inkling 2 Mini Uncensored + its vision file sized for your RAM, and the H3 I2V Director
# tab, all into ~/AI/textgen. Nothing is installed system-wide.
#
#   bash h3-director-setup.sh                    install / update everything
#   bash h3-director-setup.sh --vram-budget 7    give Inkling more VRAM next to Fooocus
#   bash h3-director-setup.sh --quant Q4_K_M     a specific model size
#   bash h3-director-setup.sh --skip-model       update the programs only
#   bash h3-director-setup.sh --help             all options
