"""Build h3-director-setup.sh: the whole installation in one file.

    python h3-i2v-promptgen/tools/build_setup_script.py

The file is a bash script that hands bazzite/install.py (with the H3 tab, rules, Chat
template and preset embedded as a base64 tar.gz) to python3. Run this again after changing
any of those files; tests/test_setup_script.py fails while the script is out of date.
"""

import base64
import gzip
import io
import re
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INSTALLER = ROOT / "bazzite" / "install.py"
OUT = ROOT / "h3-director-setup.sh"
MARK = "H3_SETUP_PYTHON"

HEADER = """#!/usr/bin/env bash
# H3 I2V Director: one-file setup for Bazzite (or any x86-64 Linux with an NVIDIA GPU).
#
# Installs TextGen, a llama.cpp new enough for Inkling 2 (CUDA, RTX 50-series ready),
# Inkling 2 Mini Uncensored + its vision file sized for your RAM, and the H3 I2V Director
# tab, all into ~/AI/textgen. Nothing is installed system-wide.
#
#   bash h3-director-setup.sh                    install / update everything
#   bash h3-director-setup.sh --vram-budget 7    give Inkling more VRAM next to Fooocus
#   bash h3-director-setup.sh --quant Q4_K_M     a specific model size
#   bash h3-director-setup.sh --skip-model       update the programs only
#   bash h3-director-setup.sh --help             all options
#
# Readable sources: h3-i2v-promptgen/ in https://github.com/pringleprng/start
# (this file is generated by tools/build_setup_script.py from bazzite/install.py and the
# files under user_data/, which are embedded below as a base64 tar.gz).
set -euo pipefail
if ! command -v python3 >/dev/null 2>&1; then
    echo "python3 is needed (Bazzite includes it)." >&2
    exit 1
fi
H3_PROG="h3-director-setup.sh" exec python3 - "$@" <<'@MARK@'
""".replace("@MARK@", MARK)


def payload() -> str:
    """Deterministic base64 tar.gz of the H3 files (same bytes for the same content)."""
    namespace: dict = {}
    files_src = re.search(r"^H3_FILES = \[.*?\]", INSTALLER.read_text(encoding="utf-8"), re.S | re.M).group(0)
    exec(files_src, namespace)  # noqa: S102 - our own constant
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tar:
        for rel in sorted(namespace["H3_FILES"]):
            data = (ROOT / rel).read_bytes()
            info = tarfile.TarInfo(rel)
            info.size, info.mode, info.mtime = len(data), 0o644, 0
            tar.addfile(info, io.BytesIO(data))
    gz = io.BytesIO()
    with gzip.GzipFile(fileobj=gz, mode="wb", mtime=0, compresslevel=9) as f:
        f.write(raw.getvalue())
    b64 = base64.b64encode(gz.getvalue()).decode("ascii")
    return "\n".join(b64[i:i + 100] for i in range(0, len(b64), 100))


def build() -> str:
    source = INSTALLER.read_text(encoding="utf-8")
    line = 'EMBEDDED_FILES = ""'
    if source.count(line) != 1:
        raise SystemExit(f"{INSTALLER} must contain exactly one line: {line}")
    source = source.replace(line, 'EMBEDDED_FILES = """\n' + payload() + '\n"""')
    if re.search(rf"^{MARK}$", source, re.M):
        raise SystemExit(f"{MARK} appears on its own line in the installer")
    source = source.split("\n", 1)[1] if source.startswith("#!") else source
    return HEADER + source.rstrip("\n") + f"\n{MARK}\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    OUT.chmod(0o755)
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")
